def fake_compiler(root: Path, target_platform: str, target_features: list[str]) -> Path:
    path = root / "fake-rustc.py"
    target = cpu.TARGETS[target_platform]
    feature_lines = "\n".join(
        f"    print('target_feature=\\\"{feature}\\\"')" for feature in target_features
    )
    path.write_text(f"""#!/usr/bin/env python3
import sys
args = sys.argv[1:]
if args == ['-Vv']:
    print('rustc 1.98.0 (fake)')
    print('host: {target['triple']}')
    print('release: 1.98.0')
elif args[:2] == ['--print', 'cfg']:
    print('target_arch=\"{target['arch']}\"')
    print('target_endian=\"little\"')
    print('target_env=\"gnu\"')
    print('target_os=\"linux\"')
    print('target_pointer_width=\"64\"')
    print('target_vendor=\"unknown\"')
{feature_lines}
else:
    raise SystemExit(0)
""",
        encoding="utf-8",
    )
    path.chmod(stat.S_IRWXU)
    return path


def verify_retained_tools(tools: Path) -> None:
    for name, expected in W5_TOOL_HASHES.items():
        path = tools / name
        if has_symlink_ancestor(path) or not path.is_file() or sha_file(path) != expected:
            raise AssertionError(f"retained W5 tool identity mismatch: {name}")


def require_connected_environment() -> None:
    if not W5_ROOT_VALUE:
        raise RuntimeError("NEBULAR_W5_CANDIDATE must be explicit for connected evidence")
    if W5_ROOT is None or not W5_ROOT.is_absolute() or has_symlink_ancestor(W5_ROOT) or not W5_ROOT.is_dir():
        raise RuntimeError("NEBULAR_W5_CANDIDATE must be a direct absolute retained candidate")
    if TEST_TMP_ROOT is None or not TEST_TMP_ROOT.is_absolute() or has_symlink_ancestor(TEST_TMP_ROOT) \
            or not TEST_TMP_ROOT.is_dir():
        raise RuntimeError("TMPDIR must be a direct absolute managed directory")
    tmp_info = TEST_TMP_ROOT.stat()
    if tmp_info.st_uid != os.getuid() or stat.S_IMODE(tmp_info.st_mode) & 0o077:
        raise RuntimeError("TMPDIR must be owner-controlled and private")
    if MAINTAINED_SOURCE is None or not MAINTAINED_SOURCE.is_absolute() \
            or has_symlink_ancestor(MAINTAINED_SOURCE) \
            or not (MAINTAINED_SOURCE / "rs9" / "nebular070_payload.py").is_file():
        raise RuntimeError("maintained RS9 source must be discoverable or explicitly supplied")
    validator_path = MAINTAINED_SOURCE / "rs9" / "nebular070_payload.py"
    if has_symlink_ancestor(validator_path) or not validator_path.is_file() \
            or sha_file(validator_path) != MAINTAINED_PORTABILITY_SHA256:
        raise RuntimeError("maintained portability validator identity mismatch")
    verify_retained_tools(W5_ROOT / "tools")


def connected_inputs(
    root: Path,
    *,
    target_args: list[str] | None = None,
    host_only: bool = False,
    test_only: bool = False,
    target_platform: str = "linux-x64",
    target_features: list[str] | None = None,
) -> dict[str, Any]:
    require_connected_environment()
    tools = W5_ROOT / "tools"
    census_tool = tools / "public-rust-census.py"
    metadata_tool = tools / "public-rust-census-metadata.py"
    target_info = cpu.TARGETS[target_platform]
    target = {"platform": target_platform, "triple": target_info["triple"]}
    features = list(target_features or target_info["features"])
    docs = w4_documents(target)
    paths = {name: root / f"{name}.json" for name in ("source-origin", "qualification", "portability", "build", "package", "runtime-receipt", "runtime-manifest")}
    raw_by_name = {
        "source-origin": docs["source_origin"], "qualification": docs["qualification"], "portability": docs["portability"],
        "build": docs["build"], "package": docs["package"], "runtime-receipt": docs["runtime_receipt"], "runtime-manifest": docs["runtime_manifest"],
    }
    for name, body in raw_by_name.items():
        write_json(paths[name], body)
    compiler = fake_compiler(root, target_platform, features)
    env = dict(os.environ)
    env.update({"NEBULAR_RUSTC_CENSUS_DIR": str(root), "NEBULAR_RUST_CENSUS_SESSION": "connected"})
    wrapper = [sys.executable, str(census_tool), str(compiler)]
    host_args = ["--crate-name", "host_probe"]
    host_run = subprocess.run(wrapper + host_args, env=env, capture_output=True, text=True, check=False)
    if host_run.returncode != 0:
        raise AssertionError(f"W5 host census wrapper invocation failed: {host_run.stderr}")
    if not host_only:
        args = ["--crate-name", "nebular_core", "--target", target["triple"], "-C", "opt-level=2"]
        args += target_args or ["-C", "ordinary-observation=on"]
        target_run = subprocess.run(wrapper + args, env=env, capture_output=True, text=True, check=False)
        if target_run.returncode != 0:
            raise AssertionError(f"W5 target census wrapper invocation failed: {target_run.stderr}")
    probe = root / "probe.json"
    result = subprocess.run(
        [sys.executable, str(metadata_tool), "probe", "--rustc", str(compiler), "--target", target["triple"], "--output", str(probe)],
        env=env, capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise AssertionError(result.stderr)
    producer = {"commit": "b" * 40, "tree": "c" * 40}
    metadata = root / "metadata.json"
    result = subprocess.run(
        [sys.executable, str(metadata_tool), "metadata", "--source-origin", str(paths["source-origin"]),
         "--build-receipt", str(paths["build"]), "--package-record", str(paths["package"]),
         "--qualification", str(paths["qualification"]), "--probe", str(probe),
         "--product-commit", cpu.PRODUCT_SOURCE["commit"], "--product-tree", cpu.PRODUCT_SOURCE["tree"],
         "--producer-commit", producer["commit"], "--producer-tree", producer["tree"],
         "--platform", target["platform"], "--triple", target["triple"], "--output", str(metadata)],
        env=env, capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise AssertionError(result.stderr)
    census = root / "census.json"
    result = subprocess.run(
        [sys.executable, str(census_tool), "aggregate", "--records", str(root), "--metadata", str(metadata),
         "--session", "connected", "--output", str(census)],
        env=env, capture_output=True, text=True, check=False,
    )
    if result.returncode != 0:
        raise AssertionError(result.stderr)
    census_raw = census.read_bytes()
    census_value = json.loads(census_raw)
    assert census_value["evidence_mode"] == "compiler-invocation-observation"
    assert any(item["target"] is None for item in census_value["records"])
    assert (host_only or any(item["target"] == target["triple"] for item in census_value["records"]))
    evidence = {
        "qualification": descriptor(paths["qualification"].read_bytes()), "portability": descriptor(paths["portability"].read_bytes()),
        "build": descriptor(paths["build"].read_bytes()), "package": descriptor(paths["package"].read_bytes()),
    }
    return {
        "input": {
            "schema": cpu.INPUT_SCHEMA, "version": "0.7.0", "test_only": test_only, "target": target,
            "cadb": dict(cpu.PRODUCT_SOURCE), "source_origin": descriptor(paths["source-origin"].read_bytes()),
            "evidence": evidence,
            "runtime": {"receipt": descriptor(paths["runtime-receipt"].read_bytes()), "manifest": descriptor(paths["runtime-manifest"].read_bytes())},
            "rust": {"census": descriptor(census_raw), "probe": descriptor(probe.read_bytes()), "metadata": descriptor(metadata.read_bytes())},
            "provider_assumptions": {
                "node": {"status": "authenticated", "version": "22.23.3", "source_sha256": "6" * 64, "binary_sha256": "7" * 64, "probe_sha256": "8" * 64},
                "sdk": {"status": "authenticated", "source_sha256": "9" * 64, "members_sha256": "a" * 64, "dispatch_sha256": "b" * 64},
            },
            "native_addon": {"present": True, "source_identity": "c" * 64, "output_identity": "d" * 64, "flags": list(cpu.ADDON_FLAGS), "compiler_provenance_sha256": "e" * 64},
        },
        "census": census_value,
        "probe": json.loads(probe.read_bytes()),
        "tools": {"census": census_tool, "metadata": metadata_tool},
    }


def mutate_actual_probe(connected: dict[str, Any], mutate: Any) -> None:
    probe = json.loads(connected["input"]["rust"]["probe"]["raw"].decode("utf-8"))
    probe.pop("identity")
    mutate(probe)
    probe["identity"] = sha(compact(probe))
    probe_descriptor = descriptor(json_bytes(probe))
    connected["input"]["rust"]["probe"] = probe_descriptor

    metadata = json.loads(connected["input"]["rust"]["metadata"]["raw"].decode("utf-8"))
    metadata.pop("identity")
    metadata["compiler_probe"]["identity"] = probe["identity"]
    metadata["identity"] = sha(compact(metadata))
    metadata_descriptor = descriptor(json_bytes(metadata))
    connected["input"]["rust"]["metadata"] = metadata_descriptor

    census = json.loads(connected["input"]["rust"]["census"]["raw"].decode("utf-8"))
    census.pop("identity")
    census["metadata_sha256"] = metadata_descriptor["sha256"]
    census["identity"] = sha(compact(census))
    connected["input"]["rust"]["census"] = descriptor(json_bytes(census))


@unittest.skipUnless(W5_ROOT_VALUE, "connected W5 evidence requires NEBULAR_W5_CANDIDATE")
class PublicCpuAssemblerTests(unittest.TestCase):
    def test_controlled_w5_cli_with_w4_schema_fixture(self) -> None:
        with tempfile.TemporaryDirectory(prefix="nebular070-cpu4-", dir=str(TEST_TMP_ROOT)) as temp:
            connected = connected_inputs(Path(temp))
            result = assemble(connected)
        self.assertEqual(result["baseline"], "x86-64-v1")
        self.assertEqual(result["properties"]["evidence_mode"], "compiler-invocation-observation")
        self.assertEqual(result["properties"]["rust"]["host_or_probe_record_count"], 1)
        self.assertEqual(result["properties"]["rust"]["target_record_count"], 1)
        self.assertEqual(result["properties"]["rust"]["census_evidence_mode"], "compiler-invocation-observation")
        self.assertEqual(result["properties"]["rust"]["cfg_target_features"], ["fxsr", "sse", "sse2"])
        self.assertEqual(result["properties"]["binary_isa_floor"], "unresolved")
        self.assertFalse(result["properties"]["admission"]["stage_a"])
        self.assertFalse(result["properties"]["native_addon"]["rust_census_proves_addon"])
        self.assertEqual(result["identity"], cpu._digest({key: value for key, value in result.items() if key != "identity"}))

    def test_arm_reviewed_feature_sets_are_accepted(self) -> None:
        for features in (["neon"], ["fp-armv8", "neon"]):
            with self.subTest(features=features), tempfile.TemporaryDirectory(
                prefix="nebular070-cpu5-", dir=str(TEST_TMP_ROOT),
            ) as temp:
                connected = connected_inputs(
                    Path(temp), target_platform="linux-arm64", target_features=list(features),
                )
                result = assemble(connected)
                self.assertEqual(result["baseline"], "armv8-a+neon")
                self.assertEqual(result["target"], "aarch64-unknown-linux-gnu")
                self.assertEqual(result["properties"]["rust"]["cfg_target_features"], list(features))

    def test_arm_advanced_feature_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory(prefix="nebular070-cpu5-", dir=str(TEST_TMP_ROOT)) as temp:
            connected = connected_inputs(
                Path(temp), target_platform="linux-arm64", target_features=["fp-armv8", "neon", "sve"],
            )
            with self.assertRaisesRegex(cpu.AssemblyError, "NEBULAR_CPU_PROBE"):
                assemble(connected)

    def test_actual_w5_probe_semantics_fail_closed_after_rebound(self) -> None:
        mutations = {
            "wrong-arch": lambda body: body["cfg"].__setitem__("target_arch", "aarch64"),
            "wrong-os": lambda body: body["cfg"].__setitem__("target_os", "android"),
            "wrong-environment": lambda body: body["cfg"].__setitem__("target_env", "musl"),
            "wrong-endian": lambda body: body["cfg"].__setitem__("target_endian", "big"),
            "wrong-pointer-width": lambda body: body["cfg"].__setitem__("target_pointer_width", "32"),
            "wrong-release": lambda body: body["version"].__setitem__("release", "1.97.0"),
            "wrong-native-host": lambda body: body["version"].__setitem__("host", "aarch64-unknown-linux-gnu"),
            "short-cfg-count": lambda body: body.__setitem__("cfg_count", 1),
            "duplicate-feature": lambda body: body["cfg"].__setitem__("target_feature", ["fxsr", "sse", "sse2", "sse2"]),
            "nonstring-feature": lambda body: body["cfg"]["target_feature"].__setitem__(0, 7),
            "advanced-feature": lambda body: body["cfg"].__setitem__("target_feature", ["avx2", "fxsr", "sse", "sse2"]),
        }
        for label, mutate in mutations.items():
            with self.subTest(label=label), tempfile.TemporaryDirectory(
                prefix="nebular070-cpu4-", dir=str(TEST_TMP_ROOT),
            ) as temp:
                connected = connected_inputs(Path(temp))
                mutate_actual_probe(connected, mutate)
                with self.assertRaisesRegex(cpu.AssemblyError, "NEBULAR_CPU_PROBE"):
                    assemble(connected)


def compact(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True, allow_nan=False).encode()


def sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha_file(path: Path) -> str:
    return sha(path.read_bytes())


def has_symlink_ancestor(path: Path) -> bool:
    return any(item.is_symlink() for item in (path, *path.parents))


def json_bytes(value: Any) -> bytes:
    return compact(value) + b"\n"


def descriptor(raw: bytes) -> dict[str, Any]:
    return {"raw": raw, "sha256": sha(raw)}


def write_json(path: Path, value: Any) -> bytes:
    raw = json_bytes(value)
    path.write_bytes(raw)
    return raw


def identity_body(body: dict[str, Any]) -> dict[str, Any]:
    result = dict(body)
    result["identity"] = sha(compact(body))
    return result


def rewrite_identity_document(document: dict[str, Any], mutate: Any) -> dict[str, Any]:
    body = json.loads(document["raw"].decode("utf-8"))
    identity = body.pop("identity", None)
    if identity is None:
        raise AssertionError("expected identity-bearing document")
    mutate(body)
    body["identity"] = sha(compact(body))
    return descriptor(json_bytes(body))


def rewrite_raw_document(document: dict[str, Any], mutate: Any) -> dict[str, Any]:
    body = json.loads(document["raw"].decode("utf-8"))
    mutate(body)
    return descriptor(json_bytes(body))


